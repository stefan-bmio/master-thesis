#!/usr/bin/env python3
"""Analyse a private, headerless App export; publish aggregate outputs only.

Usage: python analysis/app/analyse_app.py /path/to/self_reports.csv
Requires Python 3 and SciPy. Run from any directory.
"""
import argparse
import csv
import hashlib
import json
import math
import platform
from collections import defaultdict
from pathlib import Path
from statistics import mean, stdev

import scipy
from scipy import stats


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("source", type=Path)
    args = parser.parse_args()
    out = Path(__file__).resolve().parent / "output"
    out.mkdir(exist_ok=True)
    raw = args.source.read_bytes()
    with args.source.open(newline="", encoding="utf-8-sig") as handle:
        rows = list(csv.reader(handle))
    groups = defaultdict(lambda: defaultdict(list))
    tests = 0
    for row in rows:
        if len(row) != 4 or row[3] not in {"0", "1"}:
            raise ValueError("Expected four columns and a binary test flag")
        if row[3] == "1":
            tests += 1
            continue
        pid, condition, value, _ = row
        value = float(value)
        if not pid or condition not in {"CUE_MATCHING", "CUE_LABELING"}:
            raise ValueError("Missing participant ID or unknown condition")
        if not math.isfinite(value) or not 0 <= value <= 100:
            raise ValueError("Craving outside 0--100")
        groups[pid][condition].append(value)
    complete = [g for g in groups.values()
                if len(g["CUE_MATCHING"]) == len(g["CUE_LABELING"]) == 10]
    if len(complete) < 2:
        raise ValueError("At least two complete participants are required")
    matching = [mean(g["CUE_MATCHING"]) for g in complete]
    labeling = [mean(g["CUE_LABELING"]) for g in complete]
    differences = [round(l - m, 10) for l, m in zip(labeling, matching)]
    n = len(differences)
    delta, sd = mean(differences), stdev(differences)
    se = sd / math.sqrt(n)
    result = stats.ttest_1samp(differences, popmean=0, alternative="less")
    # Independent paired-test check guards contrast direction and aggregation.
    paired = stats.ttest_rel(labeling, matching, alternative="less")
    assert math.isclose(result.statistic, paired.statistic, abs_tol=1e-10)
    assert math.isclose(result.pvalue, paired.pvalue, abs_tol=1e-10)
    half = stats.t.ppf(.975, n - 1) * se
    summary = dict(n=n, matching_mean=mean(matching), matching_sd=stdev(matching),
                   labeling_mean=mean(labeling), labeling_sd=stdev(labeling),
                   difference=delta, difference_sd=sd, lower=delta-half,
                   upper=delta+half, upper_one_sided=delta+stats.t.ppf(.95,n-1)*se,
                   t=float(result.statistic), df=n-1, p=float(result.pvalue),
                   dz=delta/sd, negative=sum(d<0 for d in differences),
                   zero=sum(d==0 for d in differences),
                   positive=sum(d>0 for d in differences))
    flow = dict(raw_rows=len(rows), test_rows=tests, non_test_rows=len(rows)-tests,
                non_test_ids=len(groups), complete_ids=n, complete_rows=n*20,
                incomplete_ids=len(groups)-n, excluded_incomplete_rows=len(rows)-tests-n*20)
    for name, data in (("summary", summary), ("data_flow", flow)):
        with (out / (name + ".csv")).open("w", newline="") as handle:
            writer = csv.DictWriter(handle, fieldnames=list(data))
            writer.writeheader()
            writer.writerow(data)
    tex = ["% Generated by analyse_app.py; do not edit numbers manually."]
    macros = {"N": (n,0), "DF": (n-1,0), "M": (mean(matching),2),
              "L": (mean(labeling),2), "SDM": (stdev(matching),2),
              "SDL": (stdev(labeling),2), "Diff": (delta,2), "SDDiff": (sd,2),
              "Lower": (delta-half,2), "Upper": (delta+half,2),
              "UpperOneSided": (summary["upper_one_sided"],2),
              "T": (result.statistic,3), "P": (result.pvalue,3), "Dz": (delta/sd,3),
              "Negative": (summary["negative"],0), "Zero": (summary["zero"],0),
              "Positive": (summary["positive"],0),
              **{key[0].upper()+key[1:]: (value,0) for key,value in
                 {"rawRows":len(rows), "testRows":tests, "nonTestRows":len(rows)-tests,
                  "nonTestIds":len(groups), "completeRows":n*20,
                  "incompleteIds":len(groups)-n,
                  "excludedRows":len(rows)-tests-n*20}.items()}}
    for key, (value, digits) in macros.items():
        formatted = f"{value:.{digits}f}".replace(".", ",")
        tex.append("\\newcommand{\\App" + key + "}{" + formatted + "}")
    (out / "numbers.tex").write_text("\n".join(tex)+"\n")
    (out / "provenance.json").write_text(json.dumps({
        "sha256": hashlib.sha256(raw).hexdigest(), "python":platform.python_version(),
        "scipy":scipy.__version__, "alternative":"less", "alpha":.05,
        "contrast":"Labeling minus Matching", "confidence_interval":"two-sided 95%",
        "filter_order":"exclude test flag 1, then exactly 10 records per condition",
        "raw_data_published":False}, indent=2)+"\n")
    print(json.dumps({"flow":flow, "summary":summary}, indent=2))


if __name__ == "__main__":
    main()
